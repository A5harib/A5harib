# Outer Space - storyboard + narration script.
# Each scene: id, renderer type, part/unit label, visual description, items.
# Items: say lines (T = Twinkle the Star, Z = Captain Zoe, K = children), pauses, think pauses.

def say(spk, text, **kw):
    d = dict(k='say', spk=spk, text=text); d.update(kw); return d
def T(text, **kw): return say('T', text, **kw)
def Z(text, **kw): return say('Z', text, **kw)
def K(text, **kw): return say('K', text, **kw)
def P(sec, **kw):
    d = dict(k='pause', d=sec); d.update(kw); return d
def Q(text, think=4, spk='T', **kw):
    """A question to the children followed by a counted thinking pause."""
    d = say(spk, text, q=True, **kw)
    return [d, dict(k='think', d=think)]

def S(id, type, part, vis, items, **data):
    flat = []
    for it in items:
        flat.extend(it if isinstance(it, list) else [it])
    return dict(id=id, type=type, part=part, vis=vis, items=flat, data=data)

